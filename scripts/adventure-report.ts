/**
 * Prints and writes docs/ADVENTURE.md: every world of Gio's Adventure with its levels, what each level
 * teaches, how many maps it has, its par, and what happens when the reference, the naive and the wasteful
 * plans are played on the real engine. The numbers come from the same plans the tests use.
 * Run with: npm run report:adventure
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { LEVELS, playLevel, type AgeModeId, type Level, type RealmId } from '../src/logo/adventure/index.js';
import { REALMS } from '../src/ui/adventure/realms';
import { levelNumber, realmsFor } from '../src/ui/adventure/state';
import { ADVENTURE_NAIVE, ADVENTURE_REFERENCE, ADVENTURE_WASTEFUL } from '../tests/solutions/adventure';

const MODES: AgeModeId[] = ['coder', 'little'];
const MODE_NAME: Record<AgeModeId, string> = { coder: 'Turtle Coders', little: 'Little Turtles' };
/** The coding idea each world teaches. */
const IDEA: Record<RealmId, string> = {
  maze: 'Sequence, turns and fixing a bug',
  woods: 'REPEAT and nested REPEAT',
  river: 'IF, IFELSE and AHEAD',
  swamp: 'Timing with REST, moving Grumbles and fire',
  cave: 'JUMP, procedures with TO ... END and inputs (nested REPEAT for Little Turtles)',
  hills: 'Variables with MAKE (Turtle Coders only)',
  castle: 'Everything together, and recursion for Turtle Coders',
};

const mapsOf = (l: Level): number => 1 + (l.variants?.length ?? 0);
const inMode = (l: Level, mode: AgeModeId): boolean => l.modes.includes(mode);

function plans(l: Level, mode: AgeModeId) {
  const ref = ADVENTURE_REFERENCE[l.id]?.[mode];
  if (ref === undefined) throw new Error(`No reference plan for ${l.id} (${mode})`);
  const win = playLevel(l, mode, ref);
  if (win.status !== 'won' || win.stars !== 3 || win.commands !== l.par[mode]) {
    throw new Error(`Reference for ${l.id} (${mode}) does not win with 3 stars at par: ${win.status}, ${win.stars} stars, ${win.commands} commands`);
  }
  const naive = ADVENTURE_NAIVE[l.id];
  if (naive === undefined) throw new Error(`No naive plan for ${l.id}`);
  const lost = playLevel(l, mode, naive.code);
  if (lost.status === 'won') throw new Error(`Naive plan for ${l.id} (${mode}) wins`);
  const wasteful = ADVENTURE_WASTEFUL[l.id];
  const waste = wasteful === undefined ? null : playLevel(l, mode, wasteful);
  return { win, lost, waste };
}

function realmSection(realm: RealmId): string[] {
  const info = REALMS[realm];
  const out = [`## ${info.name}`, '', `${info.blurb} Teaches: ${IDEA[realm]}.`, ''];
  for (const mode of MODES) {
    const levels = LEVELS.filter((l) => l.realm === realm && inMode(l, mode));
    if (levels.length === 0) {
      out.push(`**${MODE_NAME[mode]}:** this world is not in their game.`, '');
      continue;
    }
    out.push(`**${MODE_NAME[mode]}** (${levels.length} levels)`, '', '| Level | Title | Kind | Maps | Par | Reference | Naive plan fails | Wasteful plan | Friend |', '| ---: | --- | --- | ---: | ---: | --- | --- | --- | --- |');
    for (const l of levels) {
      const p = plans(l, mode);
      const naive = ADVENTURE_NAIVE[l.id]!;
      const friend = l.friend ? (l.friend.art === 'critter' ? 'a critter' : l.friend.art) : '';
      const kind = l.kind === 'boss' ? `boss: ${l.boss!.name}` : 'level';
      const lose = p.lost.reason ?? p.lost.status;
      const waste = p.waste === null ? 'none' : `${p.waste.stars} stars, ${p.waste.commands} commands`;
      out.push(`| ${levelNumber(l, mode)} | ${l.title} | ${kind} | ${mapsOf(l)} | ${l.par[mode]} | 3 stars, ${p.win.commands} commands | ${lose} (${naive.status}) | ${waste} | ${friend} |`);
    }
    out.push('');
  }
  return out;
}

function totals(): string[] {
  const rows = MODES.map((mode) => {
    const levels = LEVELS.filter((l) => inMode(l, mode));
    const maps = levels.reduce((n, l) => n + mapsOf(l), 0);
    const bosses = levels.filter((l) => l.kind === 'boss').length;
    const friends = new Set(levels.flatMap((l) => (l.friend && l.friend.art !== 'critter' ? [l.friend.art] : [])));
    const critters = levels.filter((l) => l.friend?.art === 'critter').length;
    return `| ${MODE_NAME[mode]} | ${realmsFor(mode).length} | ${levels.length} | ${maps} | ${bosses} | ${[...friends].join(', ')} | ${critters} | ${levels.length * 3} |`;
  });
  return ['| Mode | Worlds | Levels | Maps | Bosses | Named friends | Critters | Stars to win |', '| --- | ---: | ---: | ---: | ---: | --- | ---: | ---: |', ...rows];
}

const out = [
  "# Gio's Adventure",
  '',
  'Generated by `npm run report:adventure`. Do not edit by hand.',
  '',
  'Every level has a reference plan that wins with three stars at par, a naive plan that fails for the reason shown, and (where it matters) a wasteful plan that wins with two stars. The report plays them on the real engine and stops with an error if any of them behaves differently, so the table is a check as well as a description. Par is the number of commands in the reference plan.',
  '',
  '## Totals',
  '',
  ...totals(),
  '',
  ...Object.keys(REALMS).flatMap((r) => [...realmSection(r as RealmId)]),
].join('\n');

console.log(out);
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'ADVENTURE.md');
fs.writeFileSync(target, out, 'utf8');
console.log(`Wrote ${target}`);